func TestCanLastInsertID(t *testing.T) {
	tbl := Table{
		PKey:    &PrimaryKey{Columns: []string{"id"}},
		Columns: []Column{{Name: "id", Type: "int64", Default: "auto"}},
	}
	if !tbl.CanLastInsertID() {
		t.Error("should be able to use last insert id")
	}

	tbl2 := Table{
		PKey:    &PrimaryKey{Columns: []string{"id"}},
		Columns: []Column{{Name: "id", Type: "string", Default: "uuid()"}},
	}
	if tbl2.CanLastInsertID() {
		t.Error("string PK should not support last insert id")
	}
}

