func TestDetectManyToManyRelationships(t *testing.T) {
	tables := []Table{
		{Name: "users", PKey: &PrimaryKey{Columns: []string{"id"}}},
		{Name: "tags", PKey: &PrimaryKey{Columns: []string{"id"}}},
		{
			Name:        "user_tags",
			IsJoinTable: true,
			PKey:        &PrimaryKey{Columns: []string{"user_id", "tag_id"}},
			FKeys: []ForeignKey{
				{Table: "user_tags", Column: "user_id", ForeignTable: "users", ForeignColumn: "id"},
				{Table: "user_tags", Column: "tag_id", ForeignTable: "tags", ForeignColumn: "id"},
			},
		},
	}
	rels := DetectToManyRelationships("users", tables)
	if len(rels) != 1 {
		t.Fatalf("expected 1 many-to-many relationship, got %d", len(rels))
	}
	if !rels[0].ToJoinTable {
		t.Error("expected ToJoinTable to be true")
	}
	if rels[0].JoinTable != "user_tags" {
		t.Errorf("expected join table 'user_tags', got %q", rels[0].JoinTable)
	}
	if rels[0].ForeignTable != "tags" {
		t.Errorf("expected foreign table 'tags', got %q", rels[0].ForeignTable)
	}
}

