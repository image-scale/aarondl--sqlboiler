type State struct {
	Config        *Config
	Driver        schema.Driver
	Schema        string
	Tables        []schema.Table
	Dialect       schema.Dialect
	Templates     *TemplateList
	TestTemplates *TemplateList
}

type TemplateList struct {
	*template.Template
}

func (tl *TemplateList) Names() []string {
	if tl == nil || tl.Template == nil {
		return nil
	}
	tmpls := tl.Template.Templates()
	names := make([]string, 0, len(tmpls))
	for _, t := range tmpls {
		if t.Name() != "" {
			names = append(names, t.Name())
		}
	}
	sort.Strings(names)
	return names
}

type TemplateData struct {
	Tables         []schema.Table
	Table          schema.Table
	Aliases        Aliases
	PkgName        string
	Schema         string
	DriverName     string
	Dialect        schema.Dialect
	LQ             string
	RQ             string
	AddGlobal      bool
	AddPanic       bool
	AddSoftDeletes bool
	AddEnumTypes   bool
	NoContext      bool
	NoHooks        bool
	NoTests        bool
	Tags           []string
	TagIgnore      []string
	StructTagCases StructTagCases
	RelationTag    string
	AutoColumns    AutoColumns
}

func NewState(config *Config) (*State, error) {
	s := &State{
		Config: config,
	}
	return s, nil
}

func (s *State) Run() error {
	data := &TemplateData{
		Tables:         s.Tables,
		Aliases:        s.Config.Aliases,
		PkgName:        s.Config.PkgName,
		Schema:         s.Schema,
		DriverName:     s.Config.DriverName,
		Dialect:        s.Dialect,
		LQ:             string(rune(s.Dialect.LQ)),
		RQ:             string(rune(s.Dialect.RQ)),
		AddGlobal:      s.Config.AddGlobal,
		AddPanic:       s.Config.AddPanic,
		AddSoftDeletes: s.Config.AddSoftDeletes,
		AddEnumTypes:   s.Config.AddEnumTypes,
		NoContext:      s.Config.NoContext,
		NoHooks:        s.Config.NoHooks,
		NoTests:        s.Config.NoTests,
		Tags:           s.Config.Tags,
		TagIgnore:      s.Config.TagIgnore,
		StructTagCases: s.Config.StructTagCases,
		RelationTag:    s.Config.RelationTag,
		AutoColumns:    s.Config.AutoColumns,
	}

	if s.Templates != nil {
		for _, tbl := range s.Tables {
			if tbl.IsJoinTable {
				continue
			}
			data.Table = tbl
			for _, name := range s.Templates.Names() {
				if err := ExecuteTemplate(s.Templates.Template, name, data); err != nil {
					return fmt.Errorf("executing template %s for table %s: %w", name, tbl.Name, err)
				}
			}
		}
	}
	return nil
}

func ExecuteTemplate(t *template.Template, name string, data any) error {
	var buf bytes.Buffer
	if err := t.ExecuteTemplate(&buf, name, data); err != nil {
		return err
	}
	return nil
}

func ExecuteTemplateToBytes(t *template.Template, name string, data any) ([]byte, error) {
	var buf bytes.Buffer
	if err := t.ExecuteTemplate(&buf, name, data); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func FormatGoSource(src []byte) ([]byte, error) {
	formatted, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("format error: %w\nsource:\n%s", err, addLineNumbers(src))
	}
	return formatted, nil
}

func addLineNumbers(src []byte) string {
	lines := bytes.Split(src, []byte("\n"))
	var buf strings.Builder
	for i, line := range lines {
		fmt.Fprintf(&buf, "%4d: %s\n", i+1, line)
	}
	return buf.String()
}

func WriteOutput(outFolder, fileName string, content []byte, goFormat bool) error {
	if err := os.MkdirAll(outFolder, 0755); err != nil {
		return err
	}

	if goFormat && strings.HasSuffix(fileName, ".go") {
		formatted, err := FormatGoSource(content)
		if err != nil {
			return err
		}
		content = formatted
	}

	return os.WriteFile(filepath.Join(outFolder, fileName), content, 0644)
}

func BuildFileHeader(pkgName string, imps importers.Set) []byte {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by sqlboiler. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)
	formatted := imps.Format()
	if len(formatted) > 0 {
		buf.Write(formatted)
		buf.WriteString("\n")
	}
	return buf.Bytes()
}

func LoadTemplatesFromFS(fsys fs.FS, root string, funcMap template.FuncMap) (*TemplateList, error) {
	t := template.New("").Funcs(funcMap)

	err := fs.WalkDir(fsys, root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		if !strings.HasSuffix(path, ".tpl") {
			return nil
		}

		data, err := fs.ReadFile(fsys, path)
		if err != nil {
			return err
		}

		name := strings.TrimPrefix(path, root+"/")
		name = strings.TrimSuffix(name, ".tpl")

		_, err = t.New(name).Parse(string(data))
		return err
	})
	if err != nil {
		return nil, err
	}
	return &TemplateList{Template: t}, nil
}

func LoadTemplatesFromDir(dir string, funcMap template.FuncMap) (*TemplateList, error) {
	t := template.New("").Funcs(funcMap)

	err := filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() {
			return nil
		}
		if !strings.HasSuffix(path, ".tpl") {
			return nil
		}

		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}

		name := strings.TrimPrefix(path, dir+string(os.PathSeparator))
		name = strings.TrimSuffix(name, ".tpl")
		name = filepath.ToSlash(name)

		_, err = t.New(name).Parse(string(data))
		return err
	})
	if err != nil {
		return nil, err
	}
	return &TemplateList{Template: t}, nil
}

func GetOutputFilename(tableName string, isTest bool) string {
	name := strings.ReplaceAll(tableName, string(os.PathSeparator), "_")
	if strings.HasPrefix(name, "_") {
		name = "und" + name
	}
	if isTest {
		name += "_test"
	}
	return name + ".go"
}

func DefaultTemplateFuncs() template.FuncMap {
	return template.FuncMap{
		"titleCase":  titleCase,
		"camelCase":  camelCase,
		"singular":   singularize,
		"plural":     pluralize,
		"quoteWrap":  func(s string) string { return fmt.Sprintf(`"%s"`, s) },
		"join":       strings.Join,
		"containsAny": func(s []string, items ...string) bool {
			m := make(map[string]struct{}, len(s))
			for _, v := range s {
				m[v] = struct{}{}
			}
			for _, item := range items {
				if _, ok := m[item]; ok {
					return true
				}
			}
			return false
		},
		"isPrimitive":     IsPrimitive,
		"isNullPrimitive": IsNullPrimitive,
	}
}
